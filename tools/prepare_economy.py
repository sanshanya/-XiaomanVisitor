"""Compile the good-ending rules, translations and native paper definitions offline."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'story/留下路线.json'


def read():
    data = json.loads(SOURCE.read_text(encoding='utf-8'))
    assert data['schema'] == 1
    assert set(data['ui']) == {'zh', 'ja', 'en'}
    assert all(set(data['ui'][lang]) == set(data['ui']['zh']) for lang in ('ja', 'en'))
    assert len({r['key'] for r in data['lines']}) == len(data['lines'])
    assert all(r['zh'] and r['ja'] and r['en'] for r in data['lines'])
    import story_variants
    data['lines'] += [story_variants.unacquainted(row) for row in list(data['lines']) if row.get('unacquainted')]
    return data


def generate():
    data = read()
    config = json.loads((ROOT / 'assets/tavern-economy.json').read_text(encoding='utf-8'))
    quote = lambda value: json.dumps(value, ensure_ascii=False)
    code = ['// Generated by tools/prepare_economy.py.', 'namespace XiaomanVisitor', '{', '    public static class TavernEconomyConfig', '    {']
    for key, value in config.items():
        name = ''.join(p.title() for p in key.split('_')).replace('Bp', 'Bp')
        if type(value) is int:
            code.append(f'        public const int {name}={value};')
        elif isinstance(value, list):
            assert all(type(n) is int for n in value)
            code.append(f'        public static readonly int[] {name}=new int[] {{'+','.join(map(str,value))+'};')
    code += ['    }', '    public static class EconomyStory', '    {']
    ids = list(data['letters'])
    code.append('        public static readonly string[] LetterIds=new string[] {'+','.join(map(quote,ids))+'};')
    code += ['        public static Mood MoodFor(string key,Mood fallback)', '        {', '            switch(key) {']
    for row in data['lines']:
        code.append('                case '+quote(row['key'])+': return Mood.'+row['mood']+';')
    code += ['                default: return fallback;', '            }', '        }',
             '        public static string KeyFor(string key,bool known)', '        {', '            if (known) return key;', '            switch(key) {']
    for row in data['lines']:
        if row['key'].endswith('_unknown'):
            code.append('                case '+quote(row['key'][:-8])+': return '+quote(row['key'])+';')
    code += ['                default: return key;', '            }', '        }', '        public static string[] Opening(string branch,int chapter)', '        {', '            switch(branch+":"+chapter) {']
    for branch in ('review', 'stay'):
        for chapter in (13, 14):
            keys=[r['key'] for r in data['lines'] if r.get('branch')==branch and r.get('chapter')==chapter]
            code.append(f'                case "{branch}:{chapter}": return new string[] {{'+','.join(map(quote, keys))+'};')
    code += ['                default: return new string[0];', '            }', '        }', '    }', '}', '']
    (ROOT / 'src/Generated/TavernEconomy.Generated.cs').write_text('\n'.join(code), encoding='utf-8')
    template=json.loads((ROOT / 'package/XiaomanVisitor/Books/story_note_13.json').read_text(encoding='utf-8'))
    for key in ids:
        book=json.loads(json.dumps(template))
        book['id']=key
        book['item'].update(id='sansm.xiaoman.visitor.'+key, nameLoc=key+'_name')
        for element in book['pages'][0]['elements']:
            if element.get('id') in ('title','body','signature'):
                element['loc']=key+'_'+element['id']
        (ROOT / f'package/XiaomanVisitor/Books/{key}.json').write_text(json.dumps(book,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    return data


if __name__ == '__main__':
    generate()
