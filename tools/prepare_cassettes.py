"""Generate the cassette catalog and apply the project's music delivery profile."""
import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

import numpy as np
import soundfile as sf
import UnityPy
from mutagen.mp3 import MP3

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / "package/XiaomanVisitor"


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path, default=Path(r"D:\apps\CloudMusic\save\电台节目"))
    parser.add_argument("--game", type=Path, default=Path(r"E:\app\steam\steamapps\common\Probably Stolen"))
    args = parser.parse_args()
    catalog = json.loads((ROOT / "assets/cassettes.json").read_text(encoding="utf-8"))
    assert len(catalog) == 14
    assert len({row["key"] for row in catalog}) == len(catalog)
    assert len({row["sprite"] for row in catalog}) == len(catalog)
    env = UnityPy.load(str(args.game / "Probably Stolen_Data/resources.assets"))
    sprites = {obj.peek_name(): obj for obj in env.objects if obj.type.name == "Sprite"}
    icon_dir = ROOT / "reference/cassette-icons"
    icon_dir.mkdir(exist_ok=True)
    sounds = PACKAGE / "Sounds"
    sounds.mkdir(exist_ok=True)
    rows, icon_hashes = [], set()
    for index, track in enumerate(catalog, 1):
        if track.get("source"):
            source = Path(track["source"])
            if not source.is_file():
                raise FileNotFoundError(source)
        else:
            matches = list(args.source.glob("* " + track["title"] + ".mp3"))
            if len(matches) != 1:
                raise ValueError(f"Expected one downloaded track for {track['title']}, found {len(matches)}")
            source = matches[0]
        metadata = MP3(source)
        peak, frames = 0.0, 0
        with sf.SoundFile(source) as audio:
            for block in audio.blocks(blocksize=131072, dtype="float32", always_2d=True):
                if not np.isfinite(block).all():
                    raise ValueError(f"Non-finite audio in {source.name}")
                peak = max(peak, float(np.max(np.abs(block))))
                frames += len(block)
            seconds = frames / audio.samplerate
        if peak <= 0 or seconds < 1:
            raise ValueError(f"Empty or silent track: {source.name}")
        target = sounds / f"rain_{track['key']}.mp3"
        shutil.copyfile(source, target)
        digest = hashlib.sha256(source.read_bytes()).hexdigest()
        assert hashlib.sha256(target.read_bytes()).hexdigest() == digest
        sprite = sprites[track["sprite"]].read()
        image = sprite.image
        assert image.size == (32, 32)
        icon_hashes.add(hashlib.sha256(image.tobytes()).hexdigest())
        image.save(icon_dir / f"{track['key']}.png")
        row = dict(track, number=index, source=str(source), packaged=str(target.relative_to(PACKAGE)),
                   seconds=round(seconds, 3), sample_rate=metadata.info.sample_rate,
                   channels=metadata.info.channels, peak=round(peak, 6), sha256=digest)
        rows.append(row)
        print(f"{index:02d} {track['title']:10} {seconds:8.2f}s  {track['sprite']}  copied, decoded, verified")
    assert len(icon_hashes) == len(catalog), "Cassette appearances must be distinct"
    (ROOT / "assets/audio/cassette-manifest.json").write_text(
        json.dumps(rows, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    generated = [
        "// Generated by tools/prepare_cassettes.py from assets/cassettes.json. Do not edit by hand.",
        "namespace XiaomanVisitor", "{", "    public static partial class CassetteCollection", "    {",
        "        public static readonly CassetteTrack[] Tracks =", "        {"
    ]
    for track in catalog:
        fields = [track["key"], track["title"], track["sprite"], track.get("storyNode", "")]
        generated.append("            new CassetteTrack(" + ", ".join(json.dumps(v) for v in fields) + "),")
    generated.extend(["        };", "    }", "}", ""])
    (ROOT / "src/CassetteCatalog.Generated.cs").write_text("\n".join(generated), encoding="utf-8")
    if (ROOT / "assets/audio/music-encoding.json").is_file():
        from optimize_music import optimize
        optimize(apply=True)
    print(f"Verified {len(rows)} complete tracks and distinct native appearances; {sum(r['seconds'] for r in rows)/60:.2f} minutes.")


if __name__ == "__main__":
    main()
