"""Validate tavern art, or explicitly --render / --pack / --preview it.

scene.json is the single layout/animation input. Ordinary full verification
uses Pillow only; install requirements-tavern.txt separately to regenerate MP4.
"""
import argparse
import base64
import hashlib
import json
from pathlib import Path
import shutil

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SCENE = ROOT / 'assets/tavern-scene'
PACKAGE = ROOT / 'package/XiaomanVisitor'


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def save(path, value):
    path.write_text(json.dumps(value,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')


def current_frames():
    detail=load(SCENE/'portrait-detail.json')
    atlas_path=PACKAGE/detail['packaged']
    assert digest(atlas_path)==detail['sha256']
    atlas=Image.open(atlas_path).convert('RGBA')
    assert atlas.size==(2304,2064)
    return [atlas.crop((i%6*384,i//6*688,(i%6+1)*384,(i//6+1)*688)) for i in range(18)]


def prepare_layers(recipe):
    width,height=recipe['reference_canvas']
    background=Image.open(SCENE/recipe['background']['file']).convert('RGBA')
    enlarged=background.resize((width,height),Image.Resampling.NEAREST)
    x,y=recipe['bar_occluder']['position']; w,h=recipe['bar_occluder']['size']
    enlarged.crop((x,y,x+w,y+h)).save(SCENE/recipe['bar_occluder']['file'],optimize=True)
    for name in ('background.png','bar-occluder.png',recipe['animation']['file'],recipe['character']['lighting']['file']):
        recipe['files'][name]=digest(SCENE/name)
    save(SCENE/'scene.json',recipe)


def layout_code(recipe):
    cw,ch=recipe['reference_canvas']; content=recipe['background']['texture_size']
    encoded=recipe['background']['encoded_size']; actor=recipe['character']; bar=recipe['bar_occluder']
    constants=dict(CanvasWidth=cw,CanvasHeight=ch,ContentWidth=content[0],ContentHeight=content[1],
        EncodedWidth=encoded[0],EncodedHeight=encoded[1],ActorX=actor['position'][0],ActorY=actor['position'][1],
        ActorWidth=actor['size'][0],ActorHeight=actor['size'][1],BarX=bar['position'][0],BarY=bar['position'][1],
        BarWidth=bar['size'][0],BarHeight=bar['size'][1])
    x,y,x1,y1=Image.open(SCENE/recipe['background']['mask']).getbbox()
    constants.update(RainX=x*3,RainY=y*3,RainWidth=(x1-x)*3,RainHeight=(y1-y)*3)
    x,y,x1,y1=recipe['props']['cassette_player']['bounds']
    constants.update(TapeX=x*3,TapeY=y*3,TapeWidth=(x1-x)*3,TapeHeight=(y1-y)*3)
    code='// Generated by tools/prepare_tavern_scene.py from assets/tavern-scene/scene.json.\nnamespace XiaomanVisitor\n{\n    internal static class TavernSceneLayout\n    {\n'
    code+=''.join(f'        internal const int {key} = {value};\n' for key,value in constants.items())
    idle=recipe['character']['idle_motion']
    code+=f"        internal const float BreathPeriod = {float(idle['period_seconds']):g}f;\n"
    code+=f"        internal const float BreathLift = {float(idle['max_lift']):g}f;\n"
    code+='    }\n}\n'
    return code


def pack(recipe):
    target=PACKAGE/'Scenes/Tavern'; target.mkdir(parents=True,exist_ok=True)
    files=[]
    for name in ('background.png','bar-occluder.png',recipe['animation']['file'],recipe['character']['lighting']['file']):
        shutil.copyfile(SCENE/name,target/name)
        files.append(dict(source=name,packaged=f'Scenes/Tavern/{name}',sha256=digest(target/name),bytes=(target/name).stat().st_size))
    save(SCENE/'runtime-manifest.json',dict(schema=2,files=files,
        preview_default=False,normal_opening_implemented=False,
        static_texture_memory_bytes=(recipe['background']['texture_size'][0]*recipe['background']['texture_size'][1]
                                     +recipe['bar_occluder']['size'][0]*recipe['bar_occluder']['size'][1])*4,
        video_resolution=recipe['background']['encoded_size'],video_fps=recipe['animation']['fps'],
        video_decoder_memory='platform-dependent; not measured by file size',existing_portraits_reused=True))
    (ROOT/'src/Generated/TavernSceneLayout.Generated.cs').write_text(layout_code(recipe),encoding='utf-8')


def validate(recipe, packaged=True):
    assert recipe['schema']==2
    for name,sha in recipe['files'].items():
        assert digest(SCENE/name)==sha, name
    assert list(Image.open(SCENE/'source.png').size)==recipe['background']['texture_size']==[1671,941]
    assert Image.open(SCENE/'window-mask.png').size==(1672,942)
    assert list(Image.open(SCENE/'bar-occluder.png').size)==recipe['bar_occluder']['size']
    assert recipe['reference_canvas']==[x*3 for x in recipe['background']['texture_size']]
    assert not recipe['animation']['audio'] and recipe['animation']['cassette_meter_baked']
    assert all(not prop['interactive'] for prop in recipe['props'].values())
    idle=recipe['character']['idle_motion']
    assert idle['period_seconds']>0 and 0<idle['max_lift']<recipe['character']['position'][1]+recipe['character']['size'][1]-recipe['bar_occluder']['position'][1]
    assert all(value>=0 for value in recipe['animation']['lighting'].values())
    provenance=load(SCENE/'render.json')
    config=json.dumps({key:value for key,value in recipe.items() if key!='files'},sort_keys=True,ensure_ascii=False).encode('utf-8')
    assert provenance['config_sha256']==hashlib.sha256(config).hexdigest(), 'Rendered config is stale'
    assert provenance['renderer_sha256']==digest(ROOT/'tools/tavern_animation.py'), 'Renderer changed; explicitly render again'
    assert provenance['cassette_renderer_sha256']==digest(ROOT/'tools/tavern_cassette.py'), 'Cassette renderer changed; explicitly render again'
    assert provenance['actor_light_renderer_sha256']==digest(ROOT/'tools/tavern_actor_light.py'), 'Actor-light renderer changed; explicitly render again'
    assert provenance['source_sha256']==digest(SCENE/'source.png') and provenance['mask_sha256']==digest(SCENE/'window-mask.png')
    assert provenance['periodic_pixels_equal']
    light=load(SCENE/recipe['character']['lighting']['file'])
    assert light['schema']==2 and light['frame_count']==recipe['animation']['fps']*recipe['animation']['seconds']
    assert 1<=light['gain_scale']<=2 and light['gain_scale']==recipe['character']['lighting']['gain_scale']
    assert light['fps']==recipe['animation']['fps']
    assert light['x']==recipe['character']['lighting']['x'] and light['y']==recipe['character']['lighting']['y']
    assert len(base64.b64decode(light['rgb'],validate=True))==light['frame_count']*len(light['x'])*len(light['y'])*3
    frames=current_frames(); reference=Image.open(SCENE/'character-reference.png').convert('RGBA')
    assert reference.getchannel('A').tobytes()==frames[0].getchannel('A').tobytes()
    assert len({hashlib.sha256(frame.tobytes()).digest() for frame in frames})==18
    x,y=recipe['character']['position']; w,h=recipe['character']['size']
    cassette=recipe['props']['cassette_player']['bounds']
    assert x+w<=cassette[0]*3 or x>=cassette[2]*3, 'Actor overlaps the future cassette player'
    manifest=load(SCENE/'runtime-manifest.json')
    if packaged:
        for file in manifest['files']:
            assert digest(PACKAGE/file['packaged'])==file['sha256']==digest(SCENE/file['source'])
        assert (ROOT/'src/Generated/TavernSceneLayout.Generated.cs').read_text(encoding='utf-8')==layout_code(recipe)
    background=Image.open(SCENE/'background.png').convert('RGBA').resize(tuple(recipe['reference_canvas']),Image.Resampling.NEAREST)
    bx,by=recipe['bar_occluder']['position']; bw,bh=recipe['bar_occluder']['size']
    assert background.crop((bx,by,bx+bw,by+bh)).tobytes()==Image.open(SCENE/'bar-occluder.png').convert('RGBA').tobytes()
    return dict(schema=2,scene_files=len(manifest['files']),existing_frames=18,
        cassette_unobstructed=True,static_texture_memory_bytes=manifest['static_texture_memory_bytes'],
        video_bytes=(SCENE/recipe['animation']['file']).stat().st_size,gameplay_tested=False)


def preview(recipe):
    from tavern_actor_light import apply_preview
    background=Image.open(SCENE/'background.png').convert('RGBA').resize(tuple(recipe['reference_canvas']),Image.Resampling.NEAREST)
    light=load(SCENE/recipe['character']['lighting']['file'])
    portrait=apply_preview(current_frames()[0],light).resize(tuple(recipe['character']['size']),Image.Resampling.NEAREST)
    background.alpha_composite(portrait,tuple(recipe['character']['position']))
    background.alpha_composite(Image.open(SCENE/'bar-occluder.png').convert('RGBA'),tuple(recipe['bar_occluder']['position']))
    output=ROOT/'.dev/previews/tavern'; output.mkdir(parents=True,exist_ok=True)
    background.save(output/'scene.png',optimize=True)
    background.resize((1671,941),Image.Resampling.LANCZOS).save(output/'scene-preview.png',optimize=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--render',action='store_true')
    parser.add_argument('--pack',action='store_true')
    parser.add_argument('--preview',action='store_true')
    args=parser.parse_args(); recipe=load(SCENE/'scene.json')
    if args.render:
        from tavern_animation import render
        provenance=render(SCENE,recipe)
        save(SCENE/'render.json',provenance)
        prepare_layers(recipe)
    if args.pack:
        validate(recipe,packaged=False)
        pack(recipe)
    result=validate(recipe)
    if args.preview: preview(recipe)
    print(json.dumps(result,ensure_ascii=False,indent=2))


if __name__=='__main__': main()
